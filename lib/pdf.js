// Minimal, dependency-free PDF writer for the dispute evidence pack (text only, Helvetica, A4).
// Builds one document: the response PayPal receives, the Seller Protection checklist and every
// cited record, so the seller has a single file to keep or attach.

const esc = (t) => String(t).replace(/[^\x20-\x7E]/g, '?').replace(/([\\()])/g, '\\$1');

function wrap(text, max = 92) {
  const out = [];
  for (const para of String(text).split('\n')) {
    let line = '';
    for (const w of para.split(/\s+/)) {
      if ((line + ' ' + w).trim().length > max) { out.push(line); line = w; } else line = (line + ' ' + w).trim();
    }
    out.push(line);
  }
  return out;
}

export function evidencePdf({ title, sections }) {
  // Lay out lines: [fontSize, bold, text]
  const lines = [[16, true, title], [9, false, `Generated by SellerShield ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC`], [10, false, '']];
  for (const s of sections) {
    lines.push([12, true, s.heading]);
    for (const l of wrap(s.body)) lines.push([10, false, l]);
    lines.push([10, false, '']);
  }
  // Paginate (A4: 595x842pt, 50pt margins)
  const pages = [];
  let cur = [], y = 792;
  for (const [size, bold, text] of lines) {
    const h = size + 5;
    if (y - h < 50) { pages.push(cur); cur = []; y = 792; }
    cur.push(`BT /${bold ? 'F2' : 'F1'} ${size} Tf 50 ${y} Td (${esc(text)}) Tj ET`);
    y -= h;
  }
  pages.push(cur);

  const objs = [];
  const add = (body) => { objs.push(body); return objs.length; };
  const catalog = add(null), pagesId = add(null);
  const f1 = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  const f2 = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');
  const kids = [];
  for (const content of pages) {
    const stream = content.join('\n');
    const c = add(`<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`);
    kids.push(add(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 ${f1} 0 R /F2 ${f2} 0 R >> >> /Contents ${c} 0 R >>`));
  }
  objs[catalog - 1] = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;
  objs[pagesId - 1] = `<< /Type /Pages /Kids [${kids.map((k) => `${k} 0 R`).join(' ')}] /Count ${kids.length} >>`;

  let pdf = '%PDF-1.4\n';
  const offsets = [];
  objs.forEach((o, i) => { offsets.push(Buffer.byteLength(pdf)); pdf += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root ${catalog} 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}

// Evidence pack for one dispute proposal.
export function disputePack(p, text) {
  const prot = p.protection;
  return evidencePdf({
    title: `Dispute ${p.target}: evidence pack`,
    sections: [
      { heading: 'Response to PayPal', body: text },
      prot && { heading: `Seller Protection check: ${prot.status.replaceAll('_', ' ').toLowerCase()}`,
        body: `${prot.summary}\n${prot.checks.map((c) => `${c.pass ? '[x]' : '[ ]'} ${c.rule} (${c.detail})`).join('\n')}\n${prot.note}` },
      { heading: 'Records cited', body: (p.records || []).map((r) => `${r.ref}: ${r.source} ${r.id}\n   ${Object.entries(r.fields).map(([k, v]) => `${k}: ${v}`).join('; ')}`).join('\n') || 'None' },
    ].filter(Boolean),
  });
}
